// Render the existing Web Audio recipes to bundled PCM files for native playback.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/sound.ts'), 'utf8');
const names = [...source.matchAll(/case '([^']+)':/g)].map((m) => m[1]);
const recipe = ts.transpileModule(source.slice(source.indexOf('export function play')), {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText;
const out = path.join(root, 'assets/sounds');
fs.mkdirSync(out, { recursive: true });
const rate = 22050;

for (const name of names) {
  const events = [];
  const scope = {
    exports: {}, muted: false,
    tone: (freq, dur, type = 'square', vol = 0.08, at = 0, slideTo) => events.push({ freq, dur, type, vol, at, slideTo }),
    noise: (dur, vol = 0.12, at = 0) => events.push({ dur, vol, at, type: 'noise' }),
  };
  vm.runInNewContext(recipe, scope);
  scope.exports.play(name);
  if (!events.length) throw new Error(`No audio recipe for ${name}`);
  const count = Math.ceil((Math.max(...events.map((e) => e.at + e.dur)) + 0.03) * rate);
  const samples = new Float32Array(count);
  let seed = 42;
  for (const e of events) {
    let phase = 0;
    for (let i = 0; i < Math.floor(e.dur * rate); i++) {
      const progress = i / (e.dur * rate);
      const hz = e.slideTo ? e.freq * Math.pow(e.slideTo / e.freq, progress) : e.freq;
      phase += (hz || 0) / rate;
      const p = phase % 1;
      seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
      const wave = e.type === 'noise' ? seed / 2147483648 - 1
        : e.type === 'sine' ? Math.sin(phase * 2 * Math.PI)
        : e.type === 'triangle' ? 1 - 4 * Math.abs(p - 0.5)
        : e.type === 'sawtooth' ? 2 * p - 1 : p < 0.5 ? 1 : -1;
      const gain = e.type === 'noise' ? e.vol * (1 - progress) : e.vol * Math.pow(0.0001 / e.vol, progress);
      samples[Math.floor(e.at * rate) + i] += wave * gain;
    }
  }
  const wav = Buffer.alloc(44 + count * 2);
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(rate, 24); wav.writeUInt32LE(rate * 2, 28);
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
  wav.write('data', 36); wav.writeUInt32LE(count * 2, 40);
  samples.forEach((v, i) => wav.writeInt16LE(Math.round(Math.max(-1, Math.min(1, v)) * 32767), 44 + i * 2));
  fs.writeFileSync(path.join(out, `${name}.wav`), wav);
}
fs.writeFileSync(path.join(root, 'src/nativeSounds.ts'),
  '// Generated by scripts/generate-native-sounds.cjs.\nexport const nativeSounds = {\n' +
  names.map((n) => `  ${n}: require('../assets/sounds/${n}.wav'),`).join('\n') + '\n} as const;\n');
console.log(`Generated ${names.length} native sounds.`);
