export const FLUENT_CDN = 'https://cdn.jsdelivr.net/gh/microsoft/fluentui-emoji@main/assets/';
const fluentPath = (folder: string) => `${encodeURIComponent(folder)}/3D/${folder.toLowerCase().replace(/ /g, '_')}_3d.png`;
/** địa chỉ hình 3D của một món */
export const pokeImageUrl = (p: Pick<PokeItem, 'fluent'>) => FLUENT_CDN + p.fluent;

export const POKES: readonly PokeItem[] = RAW.map(([id, name, folder, emoji, template, price, category, nice]) => ({
  id, name, emoji, template, category,
  fluent: fluentPath(folder),
  tier: price > 0 ? 'ruby' : 'free',
  ...(price > 0 ? { price } : {}),
  ...(nice ? { nice: true } : {}),
}));

const BY_ID = new Map(POKES.map((p) => [p.id, p]));
/** món chọc theo id; undefined nếu không có trong kho */
export const pokeItem = (id: unknown): PokeItem | undefined => (typeof id === 'string' ? BY_ID.get(id) : undefined);
export const isHardPoke = (p: PokeItem) => HARD_POKE_TEMPLATES.includes(p.template);

