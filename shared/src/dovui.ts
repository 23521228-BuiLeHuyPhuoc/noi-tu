type QTuple = [DoVuiQuestionLevel, string, string, string, string, string, 0 | 1 | 2 | 3, string];

function qs(topic: DoVuiTopicId, category: string, rows: QTuple[]): DoVuiQuestion[] {
  return rows.map(([difficulty, q, a, b, c, d, correct, explain]) => ({
    topic,
    category,
    difficulty,
    q,
    options: [a, b, c, d],
    correct,
    explain,
  }));
}

